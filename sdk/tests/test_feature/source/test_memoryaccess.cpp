static int g_pinVec = 0;

// The contribution rule, ALLOC, returned references and the opcodes calls bring in
static bool TestCallPins()
{
	bool fail = false;
	COutStream out;
	asIScriptEngine *engine = CreateEngine(out);
	RegisterTestNatives(engine);
	int r;
	r = engine->RegisterObjectType("vec", sizeof(int), asOBJ_VALUE | asOBJ_POD | asOBJ_APP_PRIMITIVE); assert( r >= 0 );
	r = engine->RegisterObjectProperty("vec", "int x", 0); assert( r >= 0 );
	r = engine->RegisterObjectMethod("vec", "void set()", asFUNCTION(VecSet), asCALL_CDECL_OBJLAST); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_THIS);
	r = engine->RegisterGlobalProperty("vec rv", &g_pinVec); assert( r >= 0 );
	asIScriptModule *mod = BuildModule(engine, "callpins",
		"int g; \n"
		"int counter; \n"
		"class W { int x; void setX() { x = 1; } } \n"
		"W gw; \n"
		"void callOnGlobal() { gw.setX(); } \n"
		"class HasW { W w; void go() { w.setX(); } } \n"
		"vec gv; \n"
		"void setGv() { gv.set(); } \n"
		"void setRv() { rv.set(); } \n"
		"void setLocal() { vec a; a.set(); } \n"
		"class HasV { vec v; void go() { v.set(); } } \n"
		"void copyVec() { vec a; gv = a; } \n"
		"K3@ mk() { return K3(); } \n"
		"int passG() { return pureFnInt(g); } \n"
		"int readConfig() { return config(); } \n"
		"int &refG() { return g; } \n"
		"void writeRefG() { refG() = 1; } \n"
		"class K3 { int v; K3() { v = 1; } } \n"
		"class K2 { K2() { counter = 1; } } \n"
		"void outInt(int &out o) { o = 1; } \n"
		"void callOut() { int x; outInt(x); } \n");
	if( mod == 0 )
	{
		TEST_FAILED;
	}
	else
	{
		EXPECT_ACCESS(MethodOf(mod, "W", "void setX()"), asMA_NONE, asMA_THIS);
		// setX's This lands on the module global's object. The compiler
		// keeps the object alive in a temporary (RefCpyV ... FREE).
		EXPECT_ACCESS(mod->GetFunctionByDecl("void callOnGlobal()"), asMA_MODULE, asMA_MODULE);
		// The callee's This lands on an owned member's object (RDSPtr reads this)
		EXPECT_ACCESS(MethodOf(mod, "HasW", "void go()"), asMA_THIS, asMA_OWNED);
		// ... on a module global's object (PshGPtr reads the global's storage)
		EXPECT_ACCESS(mod->GetFunctionByDecl("void setGv()"), asMA_MODULE, asMA_MODULE);
		// ... on a registered global's object
		EXPECT_ACCESS(mod->GetFunctionByDecl("void setRv()"), asMA_ENGINE, asMA_ENGINE);
		// ... on a local stored inline in the frame
		EXPECT_ACCESS(mod->GetFunctionByDecl("void setLocal()"), asMA_NONE, asMA_NONE);
		// ... and on a value member stored inline in `this`
		EXPECT_ACCESS(MethodOf(mod, "HasV", "void go()"), asMA_NONE, asMA_THIS);
		// COPY writes the global's object; loading its pointer reads the global
		EXPECT_ACCESS(mod->GetFunctionByDecl("void copyVec()"), asMA_MODULE, asMA_MODULE);
		// CALL of a factory stub, STOREOBJ, LOADOBJ
		EXPECT_ACCESS(mod->GetFunctionByDecl("K3@ mk()"), asMA_NONE, asMA_NONE);
		// PshG4 reads the module global for the argument
		EXPECT_ACCESS(mod->GetFunctionByDecl("int passG()"), asMA_MODULE, asMA_NONE);
		// WorldStable passes through a call unchanged
		EXPECT_ACCESS(mod->GetFunctionByDecl("int readConfig()"), asMA_WORLD_STABLE, asMA_NONE);
		// Returning a reference exposes what it points to, though taking the address reads nothing
		EXPECT_ACCESS(mod->GetFunctionByDecl("int& refG()"), asMA_MODULE, asMA_NONE);
		EXPECT_ACCESS(mod->GetFunctionByDecl("void writeRefG()"), asMA_MODULE, asMA_MODULE);
		// ALLOC: the constructor's This lands on a fresh object, LOADOBJ hands it over
		asITypeInfo *k3 = mod->GetTypeInfoByName("K3");
		asITypeInfo *k2 = mod->GetTypeInfoByName("K2");
		if( k3 == 0 || k2 == 0 )
		{
			TEST_FAILED;
		}
		else
		{
			EXPECT_ACCESS(k3->GetFactoryByIndex(0), asMA_NONE, asMA_NONE);
			EXPECT_ACCESS(k2->GetFactoryByIndex(0), asMA_NONE, asMA_MODULE);
		}
		// VAR and GETREF pass the address of a temporary
		EXPECT_ACCESS(mod->GetFunctionByDecl("void callOut()"), asMA_NONE, asMA_NONE);
		EXPECT_NO_WORLD_STABLE_WRITE(mod);
	}
	engine->ShutDownAndRelease();
	return fail;
}

// Releases count only when they may be the last one, and only for what
// destruction does outside the dying object
static bool TestDestruction()
{
	bool fail = false;
	COutStream out;
	asIScriptEngine *engine = CreateEngine(out);
	RegisterTestNatives(engine);
	int r = engine->RegisterObjectBehaviour("Buf", asBEHAVE_LIST_FACTORY, "Buf@ f(int &in) {repeat int}", asFUNCTION(BufListFactory), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	// A host type whose Release, when it destroys, touches engine state
	r = engine->RegisterObjectType("Rel", 0, asOBJ_REF); assert( r >= 0 );
	r = engine->RegisterObjectBehaviour("Rel", asBEHAVE_FACTORY, "Rel@ f()", asFUNCTION(BufFactory), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectBehaviour("Rel", asBEHAVE_ADDREF, "void f()", asMETHOD(CBuf, AddRef), asCALL_THISCALL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectBehaviour("Rel", asBEHAVE_RELEASE, "void f()", asMETHOD(CBuf, Release), asCALL_THISCALL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_ENGINE, asMA_ENGINE);
	// The VM releases an auto handle argument after the native returns
	r = engine->RegisterGlobalFunction("void sinkRel(Rel@+)", asFUNCTION(SinkRel), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	// A template whose declared Release is shared by every instance, so it
	// cannot say what destroying the elements of one instance runs
	r = engine->RegisterObjectType("tmpl<class T>", 0, asOBJ_REF | asOBJ_TEMPLATE); assert( r >= 0 );
	r = engine->RegisterObjectBehaviour("tmpl<T>", asBEHAVE_TEMPLATE_CALLBACK, "bool f(int&in, bool&out)", asFUNCTION(TmplCallbackGeneric), asCALL_GENERIC); assert( r >= 0 );
	r = engine->RegisterObjectBehaviour("tmpl<T>", asBEHAVE_FACTORY, "tmpl<T>@ f(int&in)", asFUNCTION(TmplFactoryGeneric), asCALL_GENERIC); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectBehaviour("tmpl<T>", asBEHAVE_ADDREF, "void f()", asFUNCTION(TmplNoopGeneric), asCALL_GENERIC); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectBehaviour("tmpl<T>", asBEHAVE_RELEASE, "void f()", asFUNCTION(TmplNoopGeneric), asCALL_GENERIC); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	asIScriptModule *mod = BuildModule(engine, "destruction",
		"int counter; \n"
		"class D { ~D() { counter++; } } \n"
		"class Q { } \n"
		"D@ gd; \n"
		"class E \n"
		"{ \n"
		"  Q@ q; \n"
		"  void copyOnly() { D@ local = gd; } \n"
		"  void copyAndDrop() { D@ local = gd; @q = null; } \n"
		"  void copyThenKill() { D@ local = gd; Z z; } \n"
		"} \n"
		"void fresh() { D d; } \n"
		"class T { int x; ~T() { x = 0; } } \n"
		"void freshClean() { T t; } \n"
		"funcdef void CB(); \n"
		"void nop() {} \n"
		"CB@ make() { return nop; } \n"
		"void ownedFuncdef() { CB@ cb = make(); } \n"
		"void spin(D@ h) { while( true ) {} } \n"
		"void spinFor(D@ h) { for(;;) {} } \n"
		"void listInit() { Buf b = {1, 2, 3}; } \n"
		"class B2 { } \n"
		"class D2 : B2 { ~D2() { counter++; } } \n"
		"void takeB(B2@ b) { } \n"
		"interface I3 { } \n"
		"class C3 : I3 { ~C3() { counter++; } } \n"
		"void takeI(I3@ i) { } \n"
		"class Z { Q@ h; ~Z() { @h = null; } } \n"
		"void passRel() { sinkRel(Rel()); } \n"
		"void tmplOfD() { tmpl<D@> t; } \n"
		"void tmplOfInt() { tmpl<int> t; } \n");
	if( mod == 0 )
	{
		TEST_FAILED;
	}
	else
	{
		// Balanced: gd still holds the object, so the release cannot destroy it
		EXPECT_ACCESS(MethodOf(mod, "E", "void copyOnly()"), asMA_MODULE, asMA_NONE);
		// Dropping any stored handle voids that argument
		EXPECT_ACCESS(MethodOf(mod, "E", "void copyAndDrop()"), asMA_MODULE, asMA_MODULE);
		// ~Z's own effects stay on the dying Z, but it clears a stored handle,
		// so the balanced release of `local` may be the last one
		EXPECT_ACCESS(MethodOf(mod, "E", "void copyThenKill()"), asMA_MODULE, asMA_MODULE);
		EXPECT_ACCESS(mod->GetFunctionByDecl("void fresh()"), asMA_MODULE, asMA_MODULE);
		// The dying object's own memory is private
		EXPECT_ACCESS(mod->GetFunctionByDecl("void freshClean()"), asMA_NONE, asMA_NONE);
		EXPECT_ACCESS(mod->GetFunctionByDecl("CB@ make()"), asMA_NONE, asMA_NONE);
		EXPECT_ACCESS(mod->GetFunctionByDecl("void ownedFuncdef()"), asMA_PROGRAM, asMA_PROGRAM);
		// The compiler does not fold the loop test (SetV1; JLowZ), so the FREE of
		// `h` after the loop is reachable as far as the bytecode shows
		EXPECT_ACCESS(mod->GetFunctionByDecl("void spin(D@)"), asMA_MODULE, asMA_MODULE);
		// Here the loop is a bare JMP and no RET is reachable, so only an abort
		// or exception releases `h`, and that may run ~D
		EXPECT_ACCESS(mod->GetFunctionByDecl("void spinFor(D@)"), asMA_MODULE, asMA_MODULE);
		// The buffer's pattern names only ints, and Buf's declared Release is None
		EXPECT_ACCESS(mod->GetFunctionByDecl("void listInit()"), asMA_NONE, asMA_NONE);
		// A handle of static type B2 may hold a D2, whose destructor writes a global
		EXPECT_ACCESS(mod->GetFunctionByDecl("void takeB(B2@)"), asMA_MODULE, asMA_MODULE);
		// ... and one of interface type I3 any class implementing it
		EXPECT_ACCESS(mod->GetFunctionByDecl("void takeI(I3@)"), asMA_MODULE, asMA_MODULE);
		// The fresh Rel moves into the native's argument (GETOBJ), and the VM
		// releases it after the call, which may run Rel's Release to destruction
		EXPECT_ACCESS(mod->GetFunctionByDecl("void passRel()"), asMA_ENGINE, asMA_ENGINE);
		// Destroying a tmpl<D@> may release the last reference to a D, whatever
		// the shared declaration of tmpl's Release says
		EXPECT_ACCESS(mod->GetFunctionByDecl("void tmplOfD()"), asMA_MODULE, asMA_MODULE);
		// A primitive subtype holds nothing to destroy
		EXPECT_ACCESS(mod->GetFunctionByDecl("void tmplOfInt()"), asMA_NONE, asMA_NONE);
		EXPECT_NO_WORLD_STABLE_WRITE(mod);
	}
	engine->ShutDownAndRelease();
	return fail;
}

class CObj
{
public:
	CObj() : refCount(1), v(0) {}
	void AddRef() { refCount++; }
	void Release() { if( --refCount == 0 ) { delete this; } }
	int refCount;
	int v;
};
static CObj *ObjFactory() { return new CObj(); }
static void Touch(CObj &o) { o.v++; }
static int Peek(const CObj &o) { return o.v; }
static const int &CfgRef() { return g_config; }

// An application function is opaque, so the caller charges what it may touch
// through its arguments at the scope those arguments have. A declaration of
// {None, None} covers only what the function reaches beyond them.
static bool TestNativeArguments()
{
	bool fail = false;
	COutStream out;
	asIScriptEngine *engine = CreateEngine(out);
	int r;
	r = engine->RegisterObjectType("Obj", 0, asOBJ_REF); assert( r >= 0 );
	r = engine->RegisterObjectBehaviour("Obj", asBEHAVE_FACTORY, "Obj@ f()", asFUNCTION(ObjFactory), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectBehaviour("Obj", asBEHAVE_ADDREF, "void f()", asMETHOD(CObj, AddRef), asCALL_THISCALL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	// Holds nothing, so destroying an Obj touches nothing outside it
	r = engine->RegisterObjectBehaviour("Obj", asBEHAVE_RELEASE, "void f()", asMETHOD(CObj, Release), asCALL_THISCALL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	r = engine->RegisterObjectProperty("Obj", "int v", asOFFSET(CObj, v)); assert( r >= 0 );
	// Writes its argument and nothing else
	r = engine->RegisterGlobalFunction("void touch(Obj &inout)", asFUNCTION(Touch), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	// Reads its argument and nothing else
	r = engine->RegisterGlobalFunction("int peek(const Obj &in)", asFUNCTION(Peek), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_NONE, asMA_NONE);
	// Returns a reference into configuration the host changes only while the VM is stopped
	r = engine->RegisterGlobalFunction("const int &cfgRef()", asFUNCTION(CfgRef), asCALL_CDECL); assert( r >= 0 );
	engine->GetFunctionById(r)->SetMemoryAccess(asMA_WORLD_STABLE, asMA_NONE);
	asIScriptModule *mod = BuildModule(engine, "nativeargs",
		"Obj g; \n"
		"Obj@ gh; \n"
		"void viaInout() { touch(g); } \n"
		"void viaInoutH() { touch(gh); } \n"
		"int viaConstIn() { return peek(g); } \n"
		"void viaLocal() { Obj o; touch(o); } \n"
		"int readCfg() { return cfgRef(); } \n");
	if( mod == 0 )
	{
		TEST_FAILED;
	}
	else
	{
		// The module global's object is written through the reference
		EXPECT_ACCESS(mod->GetFunctionByDecl("void viaInout()"), asMA_MODULE, asMA_MODULE);
		// The object the global handle refers to may be anywhere
		EXPECT_ACCESS(mod->GetFunctionByDecl("void viaInoutH()"), asMA_PROGRAM, asMA_PROGRAM);
		// A const parameter is only read
		EXPECT_ACCESS(mod->GetFunctionByDecl("int viaConstIn()"), asMA_MODULE, asMA_NONE);
		// A local object is the caller's own
		EXPECT_ACCESS(mod->GetFunctionByDecl("void viaLocal()"), asMA_NONE, asMA_NONE);
		// Reading through a reference into world-stable state reads nothing more
		EXPECT_ACCESS(mod->GetFunctionByDecl("int readCfg()"), asMA_WORLD_STABLE, asMA_NONE);
		EXPECT_NO_WORLD_STABLE_WRITE(mod);
	}
	engine->ShutDownAndRelease();
	return fail;
}

// Every function a module owns, methods included, with its packed byte
static void SnapshotAccess(asIScriptModule *mod, std::vector<asBYTE> &bytes)
{
	bytes.clear();
	for( asUINT n = 0; n < mod->GetFunctionCount(); n++ )
	{
		asEMemoryAccess r, w;
		mod->GetFunctionByIndex(n)->GetMemoryAccess(&r, &w);
		bytes.push_back(asBYTE((r << 4) | w));
	}
	for( asUINT t = 0; t < mod->GetObjectTypeCount(); t++ )
	{
		asITypeInfo *type = mod->GetObjectTypeByIndex(t);
		for( asUINT m = 0; m < type->GetMethodCount(); m++ )
		{
			asEMemoryAccess r, w;
			type->GetMethodByIndex(m, false)->GetMemoryAccess(&r, &w);
			bytes.push_back(asBYTE((r << 4) | w));
		}
	}
}

static bool TestSaveLoadAndRerun()
{
	bool fail = false;
	COutStream out;
	asIScriptEngine *engine = CreateEngine(out);
	RegisterTestNatives(engine);
	const char *code =
		"int g; \n"
		"class C { int x; void set() { x = 1; } } \n"
		"void writeG() { g = 1; } \n"
		"void callUndeclared() { undeclared(); } \n";
	asIScriptModule *mod = BuildModule(engine, "saved", code);
	if( mod == 0 )
	{
		TEST_FAILED;
		engine->ShutDownAndRelease();
		return fail;
	}

	CBytecodeStream stream(__FILE__"1");
	if( mod->SaveByteCode(&stream) < 0 )
	{
		TEST_FAILED;
	}
	asIScriptModule *loaded = engine->GetModule("loaded", asGM_ALWAYS_CREATE);
	if( loaded->LoadByteCode(&stream) < 0 )
	{
		TEST_FAILED;
	}

	const char *decls[] = { "void writeG()", "void callUndeclared()" };
	for( asUINT n = 0; n < 2; n++ )
	{
		asEMemoryAccess r, w;
		mod->GetFunctionByDecl(decls[n])->GetMemoryAccess(&r, &w);
		EXPECT_ACCESS(loaded->GetFunctionByDecl(decls[n]), r, w);
	}
	EXPECT_ACCESS(mod->GetFunctionByDecl("void writeG()"), asMA_NONE, asMA_MODULE);
	EXPECT_ACCESS(loaded->GetFunctionByDecl("void writeG()"), asMA_NONE, asMA_MODULE);
	EXPECT_ACCESS(loaded->GetFunctionByDecl("void callUndeclared()"), asMA_UNSET, asMA_UNSET);
	EXPECT_ACCESS(loaded->GetTypeInfoByName("C")->GetMethodByDecl("void set()"), asMA_NONE, asMA_THIS);

	// Bytecode saved with the debug info stripped carries the byte too
	CBytecodeStream stripped(__FILE__"2");
	if( mod->SaveByteCode(&stripped, true) < 0 )
	{
		TEST_FAILED;
	}
	asIScriptModule *loadedStripped = engine->GetModule("loadedStripped", asGM_ALWAYS_CREATE);
	if( loadedStripped->LoadByteCode(&stripped) < 0 )
	{
		TEST_FAILED;
	}
	EXPECT_ACCESS(loadedStripped->GetFunctionByDecl("void writeG()"), asMA_NONE, asMA_MODULE);
	EXPECT_ACCESS(loadedStripped->GetFunctionByDecl("void callUndeclared()"), asMA_UNSET, asMA_UNSET);

	// Detached CompileFunction products are analysed too, and the module's own functions stay as they were
	std::vector<asBYTE> before, after;
	SnapshotAccess(mod, before);
	asIScriptFunction *detached = 0;
	if( mod->CompileFunction("detached", "void d() { g = 5; }", 0, 0, &detached) < 0 )
	{
		TEST_FAILED;
	}
	EXPECT_ACCESS(detached, asMA_NONE, asMA_MODULE);
	if( detached )
	{
		detached->Release();
	}
	SnapshotAccess(mod, after);
	if( before != after )
	{
		TEST_FAILED;
	}

	// A rebuild of identical source gives identical results
	asIScriptModule *again = BuildModule(engine, "again", code);
	if( again == 0 )
	{
		TEST_FAILED;
	}
	else
	{
		EXPECT_ACCESS(again->GetFunctionByDecl("void writeG()"), asMA_NONE, asMA_MODULE);
		SnapshotAccess(again, after);
		if( before != after )
		{
			TEST_FAILED;
		}
	}

	// Re-running the pass over the same function objects: CompileGlobalVar and
	// CompileFunction(ADD_TO_MODULE) both rerun it for the whole module. Nothing
	// here touches existing code, so every byte must come out as it went in
	SnapshotAccess(mod, before);
	if( mod->CompileGlobalVar("extra", "int extra = 3;", 0) < 0 )
	{
		TEST_FAILED;
	}
	asIScriptFunction *added = 0;
	if( mod->CompileFunction("added", "void added() { g = 2; }", 0, asCOMP_ADD_TO_MODULE, &added) < 0 )
	{
		TEST_FAILED;
	}
	if( added )
	{
		added->Release();
	}
	SnapshotAccess(mod, after);
	// The added function is the only new entry, and it is last among the module functions
	if( after.size() != before.size() + 1 )
	{
		TEST_FAILED;
	}
	else
	{
		asUINT fc = mod->GetFunctionCount();
		std::vector<asBYTE> trimmed(after);
		trimmed.erase(trimmed.begin() + (fc - 1));
		if( trimmed != before )
		{
			TEST_FAILED;
		}
		EXPECT_ACCESS(mod->GetFunctionByDecl("void added()"), asMA_NONE, asMA_MODULE);
	}

	engine->ShutDownAndRelease();
	return fail;
}

// The saved stream carries each function's scopes. A build with the compiler
// recomputes them on load, so only the stream itself shows what was written.
static bool TestSaveWritesScopes()
{
	bool fail = false;
	COutStream out;
	asIScriptEngine *engine = CreateEngine(out);
	int id = engine->RegisterGlobalFunction("void nat()", asFUNCTION(NativeNoop), asCALL_CDECL); assert( id >= 0 );
	asIScriptFunction *nat = engine->GetFunctionById(id);
	nat->SetMemoryAccess(asMA_NONE, asMA_NONE);
	const char *code = "void f() { nat(); } \n";
	CBytecodeStream first(__FILE__"3");
	asIScriptModule *mod = BuildModule(engine, "written", code);
	if( mod == 0 || mod->SaveByteCode(&first) < 0 )
	{
		TEST_FAILED;
	}
	// The same source against a different declaration differs only in f's scopes
	nat->SetMemoryAccess(asMA_ENGINE, asMA_ENGINE);
	CBytecodeStream second(__FILE__"4");
	mod = BuildModule(engine, "written", code);
	if( mod == 0 || mod->SaveByteCode(&second) < 0 )
	{
		TEST_FAILED;
	}
	else
	{
		EXPECT_ACCESS(mod->GetFunctionByDecl("void f()"), asMA_ENGINE, asMA_ENGINE);
	}
	if( first.buffer.size() != second.buffer.size() || first.buffer == second.buffer )
	{
		PRINTF("the saved bytecode does not carry the scopes\n");
		TEST_FAILED;
	}
	engine->ShutDownAndRelease();
	return fail;
}

